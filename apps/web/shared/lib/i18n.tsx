export type MessageKey = keyof typeof zh;
type MessageParams = TranslationParams;

const zhStatus: Record<string, string> = {
  completed: "已完成",
  healthy: "健康",
  enabled: "已启用",
  failed: "失败",
  unhealthy: "异常",
  running: "运行中",
  queued: "排队中",
  published: "已发布",
  draft: "草稿",
  disabled: "已禁用",
  degraded: "降级",
  paused: "已暂停",
  denied: "已拒绝",
};

export function statusLabel(status: string, locale: Locale): string {
  const normalized = status.replaceAll("_", " ");
  return locale === "zh" ? (zhStatus[status] ?? normalized) : normalized;
}

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  toggleLocale: () => void;
  t: (key: MessageKey, params?: MessageParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  const applyLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    document.documentElement.lang = next === "zh" ? "zh-CN" : "en";
    document.documentElement.dataset.locale = next;
    window.localStorage.setItem("alcuin-locale", next);
  }, []);

  useEffect(() => {
    const saved = window.localStorage.getItem("alcuin-locale");
    applyLocale(saved === "zh" ? "zh" : "en");
  }, [applyLocale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    setLocale: applyLocale,
    toggleLocale: () => applyLocale(locale === "en" ? "zh" : "en"),
    t: (key, params) => formatTranslation(locale === "zh" ? zh[key] : key, key, params),
  }), [applyLocale, locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within LocaleProvider");
  return context;
}
